// The explosions and what flies out of them. `defs` are the explosions: how long each lasts, the sprites it plays
// (tools/art/sets/effects.mjs draws them) and its script: the sounds, the damage, the rubble and the debris, step
// by step. `debris` are the ways a piece can be flung, `pieces` the faces a script throws by name, and the rest
// says which explosion goes with which shot, vehicle and splash. Times and distances are in the game's 16.16 fixed
// point (65536 is one pixel or one tick). The numbers are the original game's, entered here with the owner's leave
// so that the game needs none of its files.

import { fixed } from './kit.mjs';
import { vehicles } from './vehicles.mjs';

/** A model's faces as flying pieces, in the order it draws them from one eighth of a turn. */
const flying = (m, sector) => m.sectors[sector]
  .map((i) => m.faces[i])
  .filter((f) => (f.flags >> 8) & 3)
  .map((f) => ({ cel: f.cel, add: Boolean(f.flags & 8), kind: (f.flags >> 8) & 3, offset: [0, 0, 0], v: f.v.map((k) => m.verts[k].map(fixed)) }));
const eighths = (m) => Array.from({ length: 8 }, (_, sector) => flying(m, sector));

