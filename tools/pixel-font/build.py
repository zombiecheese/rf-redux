def caps() -> dict[str, list[str]]:
    """The 5 x 7 glyphs of font.ts as rows of '#' and '.'."""
    text = SRC.read_text()
    body = text[text.index('const GLYPHS'):text.index('};', text.index('const GLYPHS'))]
    out = {}
    for m in re.finditer(r"^\s*(?:'((?:\\.|[^'])*)'|\"([^\"]*)\"|([A-Z0-9]))\s*:\s*\[([^\]]*)\]", body, re.M):
        ch = m.group(1) if m.group(1) is not None else m.group(2) if m.group(2) is not None else m.group(3)
        ch = ch.replace("\\'", "'").replace('\\\\', '\\')
        rows = [int(v.strip(), 0) for v in m.group(4).split(',') if v.strip()]
        out[ch] = [''.join('#' if r & (0x10 >> i) else '.' for i in range(5)) for r in rows] + ['.....'] * ROWS_DOWN
    return out


def glyph(rows: list[str]):
    pen = TTGlyphPen(None)
    for j, row in enumerate(rows):
        y = (ROWS_UP - 1 - j) * PX
        i = 0
        while i < len(row):
            if row[i] != '#':
                i += 1
                continue
            k = i
            while k < len(row) and row[k] == '#':
                k += 1
            x0, x1 = i * PX, k * PX
            pen.moveTo((x0, y))
            pen.lineTo((x0, y + PX))
            pen.lineTo((x1, y + PX))
            pen.lineTo((x1, y))
            pen.closePath()
            i = k
    return pen.glyph()


def main() -> None:
    table = {**caps(), **EXTRA}
    if 'A' not in table or 'a' not in table:
        sys.exit('font.ts glyphs not found')
    names = ['.notdef', 'space'] + [f'uni{ord(c):04X}' for c in table]
    fb = FontBuilder(PX * (ROWS_UP + ROWS_DOWN), isTTF=True)
    fb.setupGlyphOrder(names)
    cmap = {32: 'space', 0xA0: 'space'}
    glyphs = {'.notdef': glyph(['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####']), 'space': TTGlyphPen(None).glyph()}
    metrics = {'.notdef': (ADVANCE * PX, 0), 'space': (ADVANCE * PX, 0)}
    for c, rows in table.items():
        n = f'uni{ord(c):04X}'
        cmap[ord(c)] = n
        glyphs[n] = glyph(rows)
        metrics[n] = (ADVANCE * PX, 0)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=(ROWS_UP + 1) * PX, descent=-ROWS_DOWN * PX)
    fb.setupNameTable({'familyName': 'RF Pixel', 'styleName': 'Regular', 'copyright': 'Return Fire: Redux', 'version': 'Version 1.0'})
    fb.setupOS2(sTypoAscender=(ROWS_UP + 1) * PX, sTypoDescender=-ROWS_DOWN * PX, sTypoLineGap=0,
                usWinAscent=(ROWS_UP + 1) * PX, usWinDescent=ROWS_DOWN * PX, sxHeight=5 * PX, sCapHeight=ROWS_UP * PX)
    fb.setupPost()
    fb.font.flavor = 'woff'
    OUT.parent.mkdir(parents=True, exist_ok=True)
    fb.save(str(OUT))
    print(f'{OUT.relative_to(ROOT)}: {len(table)} glyphs')


if __name__ == '__main__':
    main()
